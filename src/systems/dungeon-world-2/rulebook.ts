import type { RichText } from "../../data/richText";
import type { CreationHints, ItemDef, ReferenceSectionDef } from "../types";
import rulebook from "./rulebook.json";

export type Band = "strong" | "weak" | "miss";

export interface Dw2PathMove {
  name: string;
  text: string;
  /** The text formatted, with buttons for its costs. */
  rich: RichText;
  trigger: string;
  stat?: string;
  outcomes?: Record<Band, RichText>;
}

export interface Dw2Path {
  id: string;
  classId: string;
  name: string;
  /** The line under the Path's heading. */
  tagline: string;
  moves: string[];
  rules: Dw2PathMove[];
}

/** A core move's text and outcomes as the rulebook writes them, by heading level. */
export interface SourceMove {
  text: RichText;
  outcomes?: Record<Band, RichText>;
}

interface Rulebook {
  paths: Dw2Path[];
  bondTexts: Record<string, string>;
  struggleTexts: Record<string, string>;
  magicItems: ItemDef[];
  gmReference: ReferenceSectionDef[];
  moves: Record<string, Partial<Record<3 | 4, SourceMove>>>;
  creationHints: Record<string, CreationHints>;
}

/** The Dungeon World 2 rulebook, generated by `npm run generate:rules`. */
const book = rulebook as unknown as Rulebook;

/** The 27 Paths, each with its five moves' rules. */
export const PATHS = book.paths;
/** Each Bond's rules text, by bond id. */
export const BOND_TEXTS = book.bondTexts;
/** Each Struggle's rules text, by struggle id. */
export const STRUGGLE_TEXTS = book.struggleTexts;
/** The rulebook's example magic items and artifacts. */
export const SOURCE_MAGIC_ITEMS = book.magicItems;
/** The GM-facing reference sections. */
export const GM_REFERENCE = book.gmReference;
/** The core moves the rulebook writes out, by move id. */
export const SOURCE_MOVES = book.moves;
/** Each class's creation hints from its rulebook pages, by class id. */
export const CLASS_CREATION_HINTS = book.creationHints;
